@cli.command("open")
@click.argument("name")
@click.option("--new", "force_new", is_flag=True,
              help="Start a fresh session instead of attaching to the running one.")
@click.option("--label", default=None,
              help="Name this parallel session. Required to address it by name later.")
@click.option("--list", "list_only", is_flag=True, help="List live sessions on the agent's host.")
def open_cmd(name: str, force_new: bool, label: str | None, list_only: bool) -> None:
    """Open a window on an agent: attach if it is running, else start it.

    Attaching is the default because an agent on the server is already alive
    with its context; starting a second one beside it splits the work in two
    and neither half knows about the other.
    """
    try:
        agent = config.resolve_agent(name)
    except ValueError as e:
        ui.error(str(e))
        sys.exit(2)
    if not agent:
        ui.error(f"no agent matches {name!r}")
        sys.exit(1)

    host = agent.get("host") or "local"
    sessions = spawn.tmux_sessions(host)

    if list_only:
        if sessions is None:
            ui.error(f"could not reach {host}")
            sys.exit(1)
        for sname in sessions:
            click.echo(f"  {sname}")
        return

    if sessions is None:
        # Unreachable is not idle. Starting a "fresh" session here would at
        # best fail and at worst duplicate one that is already running.
        ui.error(f"could not reach {host}; not starting anything. "
                 f"Check `ssh {config.resolve_host(agent).ssh_alias}` and Tailscale.")
        sys.exit(1)

    want = agent.get("session") or agent["id"]
    if want in sessions and not force_new:
        spawn.attach_window(want, host)
        ui.info(f"Attached a window to '{want}' on {host}.")
        return

    if force_new and not label:
        ui.warn("A parallel session with no --label cannot be addressed by name. "
                "Two unlabelled ones make both unreachable unambiguously.")
    try:
        spawn.open_agent(
            agent["name"], agent["path"],
            topic=label,
            harness=agent.get("harness", "claude"),
            host=host,
            session=label or agent["id"],
            config_dir=config.resolve_config_dir(agent),
        )
    except RuntimeError as e:
        ui.error(str(e))
        sys.exit(1)
    ui.info(f"Started '{agent['name']}'" + (f" (label: {label})" if label else "") + f" on {host}.")


@cli.command("grants")
@click.option("--json", "as_json", is_flag=True, help="Emit the audit as JSON.")
@click.option("--fix", is_flag=True, help="Backfill missing mcp/settings paths from each agent's account.")
@click.option("--check-files", is_flag=True, help="Also verify the config files exist on each agent's host (one SSH per host).")
def grants_cmd(as_json: bool, fix: bool, check_files: bool) -> None:
    """Audit need-to-know wiring: which agents are fenced, and how completely.

    Need-to-know has two halves (an --only-mcp file and a --settings file with
    the Bash guard) and neither works alone. This reports agents wired to only
    one, which look correct in the registry and are not. --check-files goes
    further and asks each host whether the files are actually there, because a
    recorded path to a file that was never generated fences nothing.
    """
    rows = []
    for a in config.active_agents():
        acct = a.get("account")
        want_mcp, want_settings = config.grant_paths(acct)
        rows.append({
            "name": a["name"],
            "host": a.get("host"),
            "account": acct,
            "mcp": a.get("mcp"),
            "settings": a.get("settings"),
            "expected_mcp": want_mcp,
            "expected_settings": want_settings,
        })

    if check_files:
        _check_grant_files(rows)

    for r in rows:
        if not r["account"]:
            r["state"] = "ungranted"          # no account: not fenced, by design
        elif r["mcp"] and r["settings"]:
            r["state"] = "full"
        elif r["mcp"] or r["settings"]:
            r["state"] = "HALF"               # the dangerous one
        else:
            r["state"] = "MISSING"
        if check_files and r["state"] in ("full", "HALF"):
            if r.get("files_present") is False:
                r["state"] = "NO FILES"
            elif r.get("empty_tenant"):
                # Fenced, but to nothing: no Atlas tenant of its own yet.
                r["state"] = "NO TENANT"

    if fix:
        fixed = 0
        for r in rows:
            if r["account"] and (r["mcp"] != r["expected_mcp"] or r["settings"] != r["expected_settings"]):
                config.set_fields(r["name"], mcp=r["expected_mcp"], settings=r["expected_settings"])
                ui.info(f"  {r['name']}: wired both halves for account '{r['account']}'")
                fixed += 1
        ui.info(f"Backfilled {fixed} agent(s)." if fixed else "Nothing to backfill.")
        return

    if as_json:
        click.echo(json.dumps(rows, indent=2))
        return

    width = max((len(r["name"]) for r in rows), default=4)
    for r in rows:
        acct = r["account"] or "-"
        click.echo(f"{r['name']:<{width}}  {r['state']:<9}  account={acct}")
    bad = [r for r in rows if r["state"] in ("HALF", "MISSING", "NO FILES")]
    if bad:
        ui.warn(f"{len(bad)} agent(s) with an account are not fully fenced: "
                + ", ".join(r["name"] for r in bad))
        ui.warn("Run `a-team grants --fix`, then `agent-grants` on that host to generate the files.")


EMPTY_MCP = '"mcpServers": {}'


def _check_grant_files(rows: list[dict]) -> None:
    """Ask each host, once, which of the referenced grant files exist."""
    from . import hosts as _hosts

    by_host: dict[str, list[dict]] = {}
    for r in rows:
        if r["mcp"] or r["settings"]:
            by_host.setdefault(_hosts.normalize_key(r["host"]), []).append(r)

    for host, hrows in by_host.items():
        paths = sorted({p for r in hrows for p in (r["mcp"], r["settings"]) if p})
        # One shell, one round trip. The test must expand ~ but the echo must
        # NOT: `echo ~/x` prints the expanded path, which never equals the
        # recorded string, so every file reads as absent. Echo an index and
        # map it back here instead of matching on the path text.
        # For an MCP config, existing is not the same as granting anything:
        # a file declaring an empty mcpServers fences the session to no tenant
        # at all. That is a real state, but not the one "wired" implies, so
        # report it separately rather than as a pass.
        checks = []
        for i, path in enumerate(paths):
            if "grants/mcp" in path:
                checks.append(
                    "[ -f {p} ] && {{ grep -q '{empty}' {p} "
                    "&& echo '{i}:empty' || echo '{i}:ok'; }}".format(
                        p=path, i=i, empty=EMPTY_MCP)
                )
            else:
                checks.append("[ -f {p} ] && echo '{i}:ok'".format(p=path, i=i))
        script = "; ".join(checks)
        try:
            if host == _hosts.DEFAULT_HOST:
                out = subprocess.run(["sh", "-c", script], capture_output=True,
                                     text=True, timeout=20).stdout
            else:
                alias = _hosts.all_hosts()[host].ssh_alias
                out = subprocess.run(["ssh", "-o", "ConnectTimeout=8", alias, script],
                                     capture_output=True, text=True, timeout=25).stdout
        except (subprocess.SubprocessError, KeyError, OSError) as e:
            # Unreachable is not the same as absent. Say so rather than
            # reporting every agent on that host as unfenced.
            ui.warn(f"could not check files on {host}: {e}")
            for r in hrows:
                r["files_present"] = None
            continue
        found, empty = set(), set()
        for token in out.split():
            idx, _, state = token.partition(":")
            if not idx.isdigit():
                continue
            found.add(paths[int(idx)])
            if state == "empty":
                empty.add(paths[int(idx)])
        for r in hrows:
            want = [p for p in (r["mcp"], r["settings"]) if p]
            r["files_present"] = all(p in found for p in want)
            r["missing_files"] = [p for p in want if p not in found]
            r["empty_tenant"] = bool(r["mcp"]) and r["mcp"] in empty


@cli.command("archive")
@click.argument("names", nargs=-1, required=True)
def archive_cmd(names: tuple[str, ...]) -> None:
    """Archive one or more agents: out of the picker, kept in the registry.

    Archiving clears `boot`, so an archived agent cannot come back on the next
    reboot. The folder is untouched, and the id is kept, so `unarchive` puts
    the agent back exactly as it was.
    """
    failed = False
    for name in names:
        try:
            a = config.set_status(name, "archived")
        except ValueError as e:
            ui.error(str(e))
            failed = True
            continue
        ui.info(f"Archived '{a['name']}' (folder kept, boot cleared).")
    if failed:
        sys.exit(1)


@cli.command("unarchive")
@click.argument("names", nargs=-1, required=True)
def unarchive_cmd(names: tuple[str, ...]) -> None:
    """Put archived agents back in the picker.

    `boot` is NOT restored: decide again whether it should start on reboot.
    """
    failed = False
    for name in names:
        try:
            a = config.set_status(name, "active")
        except ValueError as e:
            ui.error(str(e))
            failed = True
            continue
        ui.info(f"Reactivated '{a['name']}'. Set boot separately if it should start on reboot.")
    if failed:
        sys.exit(1)


