def _clipboard_path() -> str | None:
    """Return clipboard contents if it looks like an existing directory.

    Designed for the Finder flow: Shift+Right-click → Copy "X" as Pathname,
    then `a-team new <name>` (no path arg) picks it up automatically.
    """
    try:
        result = subprocess.run(
            ["pbpaste"], capture_output=True, text=True, timeout=2, check=True
        )
    except (subprocess.SubprocessError, FileNotFoundError):
        return None
    candidate = result.stdout.strip()
    if not candidate:
        return None
    expanded = Path(candidate).expanduser()
    if expanded.is_dir():
        return str(expanded)
    return None


def _open(
    agent: dict,
    *,
    session_mode: str = "continue",
    topic: str | None = None,
    override_harness: str | None = None,
) -> bool:
    """Launch an agent under its saved harness (or a one-time override),
    resolving the harness-appropriate account config. One place so every launch
    path stays consistent. Returns False (after printing an actionable error) if
    the chosen harness isn't installed."""
    hk = config.resolve_harness(agent, override=override_harness).key
    host = config.resolve_host(agent)
    try:
        spawn.open_agent(
            agent["name"],
            agent["path"],
            session_mode=session_mode,
            topic=topic,
            harness=hk,
            host=host.key,
            session=agent.get("id"),
            config_dir=config.resolve_config_dir(agent, harness=hk),
        )
        return True
    except RuntimeError as e:
        ui.error(str(e))
        return False


class AteamGroup(click.Group):
    """Click Group that routes unknown command names to the direct-open
    shortcut handler. Lets `a-team EA` work without colliding with the
    real subcommands."""

    def get_command(self, ctx, cmd_name):
        rv = super().get_command(ctx, cmd_name)
        if rv is not None:
            return rv

        # Unknown name — treat as direct-open shortcut.
        @click.command(name=cmd_name, help=f"Open agent '{cmd_name}'.")
        @click.option(
            "--harness",
            "harness",
            type=click.Choice(["claude", "codex"]),
            default=None,
            help="Open under this harness once (default: the agent's saved harness). "
            "Does not change the saved default.",
        )
        def shortcut(harness: str | None):
            agent = config.find_agent(cmd_name)
            if not agent:
                ui.error(f"agent not found: {cmd_name}")
                ui.console.print(
                    "[soft]Run `a-team ls` to see registered agents.[/soft]"
                )
                sys.exit(1)
            if not _open(agent, override_harness=harness):
                sys.exit(1)

        return shortcut


@click.group(
    cls=AteamGroup,
    invoke_without_command=True,
    context_settings={"help_option_names": ["-h", "--help"]},
)
@click.option("--no-splash", is_flag=True, help="Suppress the splash banner.")
@click.pass_context
def cli(ctx: click.Context, no_splash: bool) -> None:
    """Parallel Claude Code session manager. I love it when a plan comes together."""
    ctx.ensure_object(dict)
    ctx.obj["no_splash"] = no_splash

    if ctx.invoked_subcommand is None:
        run_picker(no_splash=no_splash)


@cli.command("sync")
@click.option("--dry-run", is_flag=True, help="Show what would be written, change nothing.")
def sync_cmd(dry_run: bool) -> None:
    """Write each host's boot list from the registry.

    The registry is the source of truth. A host that cannot run a-team (no
    Python package installed there) still needs to restore its own sessions
    after a reboot, so it gets a generated list it can read locally. Six files
    once described an agent and drifted within a day; this keeps it to one.
    """
    from . import config as _config
    from . import hosts as _hosts

    by_host: dict[str, list[dict]] = {}
    for a in _config.boot_agents():
        by_host.setdefault(_hosts.normalize_key(a.get("host")) or "local", []).append(a)

    if not by_host:
        click.echo("  no agents marked boot = true")
        return

    for host, agents in sorted(by_host.items()):
        lines = [
            "# GENERATED by `a-team sync` from the a-team registry. Do not edit.",
            "# Edit the registry instead, then run sync again.",
            "# tmux-name\tfolder\tremote-control-name\tmcp-config\tsettings-file",
            "# (- for none). BOTH config columns matter: the mcp file fences the",
            "# session to its tenant, the settings file denies other customers'",
            "# paths and installs the Bash guard. Neither is sufficient alone.",
        ]
        for a in sorted(agents, key=lambda x: x["name"]):
            lines.append("\t".join([
                a["session"], a["path"], a["rc"],
                a.get("mcp") or "-", a.get("settings") or "-",
            ]))
        body = "\n".join(lines) + "\n"

        target = "~/.config/session-boot/sessions.tsv"
        if dry_run:
            click.echo(f"  {host}: would write {len(agents)} agents to {target}")
            for a in sorted(agents, key=lambda x: x["name"]):
                click.echo(f"      {a['session']:<26} {a['path']}")
            continue

        if host == "local":
            path = Path.home() / ".config" / "session-boot" / "sessions.tsv"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body)
        else:
            # Written over stdin, never as a command argument: agent names are
            # user data and must not be spliced into a shell command line.
            proc = subprocess.run(
                ["ssh", host, "mkdir -p ~/.config/session-boot && cat > ~/.config/session-boot/sessions.tsv"],
                input=body, text=True, capture_output=True,
            )
            if proc.returncode != 0:
                click.echo(f"  {host}: FAILED to write ({proc.stderr.strip()[:120]})", err=True)
                continue
        click.echo(f"  {host}: wrote {len(agents)} agents to {target}")


@cli.command("all")
@click.pass_context
def all_cmd(ctx: click.Context) -> None:
    """Restore the agents marked boot (post-reboot)."""
    no_splash = ctx.obj.get("no_splash", False)
    # Archived agents are never restored, and booting is opt in: most of the
    # registry is dormant history, not things that should come back.
    boot = config.boot_agents()

    if not boot:
        ui.warn("No agents are marked boot = true. Set boot on the ones that should come back.")
        return

    if not no_splash:
        ui.print_splash(len(agents))

    ui.info(f"Restoring {len(boot)} agents…")
    spawn.open_all(boot)
    ui.info("Done.")


def _record(agent: dict) -> dict:
    """The full normalized record for an agent, as JSON-safe data.

    Agents are the main consumers of this output, so it emits every field
    rather than a hand-picked subset: a caller that has to shell out twice
    because the first call omitted `account` is a caller that will instead
    go parse agents.toml, which is what `resolve` exists to prevent.
    `ssh` is derived, not stored, and is what you actually need to reach it.
    """
    out = dict(agent)
    out["ssh"] = config.resolve_host(agent).ssh_alias
    out["status"] = agent.get("status") or "active"
    out["boot"] = bool(agent.get("boot"))
    return out


@cli.command("resolve")
@click.argument("identifier")
@click.option("--json", "as_json", is_flag=True, help="Emit the full record as JSON.")
@click.option("--field", type=click.Choice(["id", "name", "path", "harness", "host"]), default=None,
              help="Print just one field (for shell scripts).")
def resolve_cmd(identifier: str, as_json: bool, field: str | None) -> None:
    """Resolve an agent identifier (id, exact name, or alias) to its record.

    The single canonical resolver for shell helpers: instead of each script
    re-parsing agents.toml, they call this. Resolves by stable id → exact name →
    alias, refuses ambiguous matches (exit 2), and exits 1 if not found. Default
    output is the stable id; --field or --json for more.
    """
    try:
        agent = config.resolve_agent(identifier)
    except ValueError as e:  # ambiguous identifier
        ui.error(str(e))
        sys.exit(2)
    if not agent:
        ui.error(f"no agent matches {identifier!r}")
        sys.exit(1)
    if as_json:
        click.echo(json.dumps(_record(agent)))
    elif field:
        click.echo(agent[field])
    else:
        click.echo(agent["id"])


@cli.command("migrate")
@click.option("--apply", "do_apply", is_flag=True, help="Write the changes (default is a dry run).")
def migrate_cmd(do_apply: bool) -> None:
    """Backfill stable ids + harness into agents.toml (rename-safe identity).

    Dry run by default: shows exactly what would change and writes nothing.
    Pass --apply to write; the current registry is backed up to
    <name>.bak-<timestamp> first, and all other fields/tables are preserved.
    """
    report = config.migrate_registry(apply=do_apply)
    changes = report["changes"]
    if not changes:
        ui.info(f"Registry already migrated ({report['total']} agents). Nothing to do.")
        return
    verb = "Migrated" if do_apply else "Would migrate"
    ui.info(f"{verb} {len(changes)} of {report['total']} agents in {report['path']}:")
    for name, agent_id, harness in changes:
        ui.console.print(f"  [soft]{name}[/soft] → id=[bold]{agent_id}[/bold], harness={harness}")
    if do_apply:
        ui.info(f"Backup written to {report['backup']}")
        ui.info("Done. Rollback: restore the .bak file over agents.toml.")
    else:
        ui.warn("Dry run — nothing written. Re-run with --apply to write.")


@cli.command("here")
@click.argument("name", required=False, default=None)
@click.option("--category", "-c", default=None, help="Category for grouping in the picker.")
@click.option("--account", default=None, help="Claude account override (e.g. 'work'). Omit to use the category's default.")
@click.option("--harness", type=click.Choice(["claude", "codex"]), default=None, help="Harness to run this agent under (default: claude).")
@click.option("--host", default=None, help="Where the agent lives: 'local' or a host from the [hosts] table (default: local).")
def here_cmd(name: str | None, category: str | None, account: str | None, harness: str | None, host: str | None) -> None:
    """Register the current working directory as an agent.

    Name defaults to the directory's basename if omitted. Useful for adding
    an existing project folder you're already working in without typing the
    full path.

    Examples:
        cd ~/Documents/some-project && a-team here
        cd ~/Documents/some-project && a-team here MyAgent -c Work
    """
    try:
        cwd = os.getcwd()
    except OSError as e:
        ui.error(f"Can't read current directory ({e}). Try `cd ~` first.")
        sys.exit(1)
    if name is None:
        name = Path(cwd).name
    try:
        agent = config.add_agent(name, cwd, category=category, account=account, harness=harness, host=host)
    except ValueError as e:
        ui.error(str(e))
        sys.exit(1)
    cat_suffix = f", {agent['category']}" if agent.get("category") else ""
    ui.info(f"Added agent '{agent['name']}' ({agent['harness']}, host={agent['host']}{cat_suffix}) → {agent['path']}")


def _slugify(label: str) -> str:
    """Lowercase, replace runs of non-alphanumerics with single hyphens,
    trim leading/trailing hyphens. Empty string in → empty string out."""
    return config.slugify(label)


def _scratch_name() -> str:
    """Build a default scratch session name from the current timestamp."""
    return time.strftime("%Y-%m-%d_%H-%M")


def _create_scratch(label: str | None) -> dict | None:
    """Create a scratch session: timestamped folder under SCRATCH_DIR,
    registered under category=Scratch. Returns the agent
    dict, or None on failure (with an error already printed)."""
    config.SCRATCH_DIR.mkdir(parents=True, exist_ok=True)

    base = _scratch_name()
    slug = _slugify(label or "")
    name = f"{base}_{slug}" if slug else base

    # Resolve name conflicts by appending a counter.
    suffix = 1
    candidate = name
    while config.find_agent(candidate) is not None:
        suffix += 1
        candidate = f"{name}-{suffix}"
    name = candidate

    folder = config.SCRATCH_DIR / name
    try:
        folder.mkdir(parents=False, exist_ok=False)
    except OSError as e:
        ui.error(f"could not create scratch folder {folder}: {e}")
        return None

    try:
        agent = config.add_agent(
            name, str(folder), category=config.SCRATCH_CATEGORY,
        )
    except ValueError as e:
        ui.error(str(e))
        return None
    return agent


@cli.command("scratch")
@click.argument("label", required=False, default=None)
def scratch_cmd(label: str | None) -> None:
    """Create a one-off scratch session and open it immediately.

    Scratch sessions live under ~/.a-team/scratch/<timestamp>[_<label>]/,
    are registered under `category=Scratch`, and are not booted by
    `a-team all`. They appear in the picker under a 'Scratch' section
    capped at the 10 most recent (with 'Show all scratch' to expand).
    """
    agent = _create_scratch(label)
    if agent is None:
        sys.exit(1)
    ui.info(f"Created scratch '{agent['name']}' → {agent['path']}")
    _open(agent)


@cli.command("new")
@click.argument("name")
@click.argument("path", required=False, default=None)
@click.option("--category", "-c", default=None, help="Category for grouping in the picker.")
@click.option("--account", default=None, help="Claude account override (e.g. 'work'). Omit to use the category's default.")
@click.option("--harness", type=click.Choice(["claude", "codex"]), default=None, help="Harness to run this agent under (default: claude).")
@click.option("--host", default=None, help="Where the agent lives: 'local' or a host from the [hosts] table. The folder is created on that machine.")
@click.option("--sibling", "sibling_of", default=None, metavar="PARENT",
              help="Clone PARENT's host, category, account, harness and MCP grant; record the lineage.")
@click.option("--boot/--no-boot", "boot", default=None,
              help="Start this agent on reboot (`a-team all`). Default: no.")
def new_cmd(name: str, path: str | None, category: str | None, account: str | None,
            harness: str | None, host: str | None, sibling_of: str | None,
            boot: bool | None) -> None:
    """Register a new agent.

    PATH lookup order if omitted:
      1. macOS clipboard (Finder: Shift+Right-click → Copy as Pathname)
      2. Scaffold <default_parent>/<name>/ if `default_parent` is set
         (see `a-team config default-parent <path>`)

    With --sibling, the new agent inherits the parent's host, category,
    account, harness and MCP grant unless you override them explicitly, and
    records `parent` so the lineage is visible in the registry rather than
    only in whoever's memory created it.
    """
    from . import hosts as _hosts

    parent = None
    if sibling_of:
        try:
            parent = config.resolve_agent(sibling_of)
        except ValueError as e:  # ambiguous
            ui.error(str(e))
            sys.exit(2)
        if not parent:
            ui.error(f"no agent matches {sibling_of!r} to be a sibling of")
            sys.exit(1)
        # Explicit flags win; the parent only fills the gaps.
        host = host if host is not None else parent.get("host")
        category = category if category is not None else parent.get("category")
        account = account if account is not None else parent.get("account")
        harness = harness if harness is not None else parent.get("harness")

    # No --host given? Use the configured default (a-team config default-host).
    host_key = _hosts.normalize_key(host if host is not None else config.get_default_host())
    if host_key == _hosts.DEFAULT_HOST:
        resolved = _resolve_new_path(name, path)
        if resolved is None:
            sys.exit(1)
    else:
        # Remote host: do NOT resolve or scaffold against this filesystem.
        # Pass the raw path through; `~` is expanded on the REMOTE machine.
        # With no path given, mirror the local convention: ~/agents/<slug>.
        resolved = path or f"~/agents/{config.slugify(name)}"

    try:
        agent = config.add_agent(name, resolved, category=category, account=account, harness=harness, host=host_key, create_dir=True)
    except ValueError as e:
        ui.error(str(e))
        sys.exit(1)

    extra: dict = {}
    if parent:
        extra["parent"] = parent["id"]
        # The grant is the whole point of a sibling: a second session for the
        # same client must see that tenant and no other, and must be fenced off
        # other customers' folders. Derive BOTH halves from the account rather
        # than copying whichever the parent happened to have recorded.
        mcp, settings = config.grant_paths(agent.get("account"))
        if mcp:
            extra["mcp"] = mcp
            extra["settings"] = settings
    if boot:
        extra["boot"] = True
    if extra:
        agent = config.set_fields(agent["name"], **extra)
    cat_suffix = f", {agent['category']}" if agent.get("category") else ""
    ui.info(f"Added agent '{agent['name']}' ({agent['harness']}, host={agent['host']}{cat_suffix}) → {agent['path']}")
    if parent:
        ui.info(f"  sibling of '{parent['name']}'"
                + (f", sharing its MCP grant ({agent['mcp']})" if agent.get("mcp") else ""))
        ui.info("  Give it its own --label when you open it, or it cannot be addressed by name.")


def _resolve_new_path(name: str, path: str | None) -> str | None:
    """Decide the path for a new agent, given (possibly None) input.

    Behavior:
      - If `path` exists: register it as-is.
      - If `path` doesn't exist but its parent does: scaffold the folder
        and register it.
      - If `path` is missing entirely: try clipboard, then default_parent.
    Returns the resolved path string, or None if it couldn't be determined
    (in which case an error has already been printed).
    """
    if path:
        p = Path(path).expanduser()
        if p.is_dir():
            return str(p)
        if p.parent.is_dir():
            try:
                p.mkdir(parents=False, exist_ok=False)
            except OSError as e:
                ui.error(f"could not create {p}: {e}")
                return None
            ui.info(f"Created folder: {p}")
            return str(p)
        ui.error(f"path does not exist and parent is missing: {path}")
        return None

    clip = _clipboard_path()
    if clip:
        ui.info(f"Using path from clipboard: {clip}")
        return clip

    parent = config.get_default_parent()
    if parent:
        scaffolded = parent / config.slugify(name)
        try:
            scaffolded.mkdir(parents=False, exist_ok=False)
        except FileExistsError:
            if not scaffolded.is_dir():
                ui.error(f"{scaffolded} exists but is not a directory")
                return None
            ui.info(f"Using existing folder: {scaffolded}")
        else:
            ui.info(f"Created folder: {scaffolded}")
        return str(scaffolded)

    ui.error("No path argument, no valid clipboard path, and no default_parent set.")
    ui.console.print(
        "[soft]Set one with: a-team config default-parent ~/agents[/soft]"
    )
    return None


