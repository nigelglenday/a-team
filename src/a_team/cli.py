@cli.command("ls")
@click.option("--all", "show_all", is_flag=True, help="Include archived agents.")
@click.option("--json", "as_json", is_flag=True, help="Emit full records as a JSON array.")
@click.option("--boot", "boot_only", is_flag=True, help="Only agents marked boot.")
@click.option("--host", default=None, help="Only agents on this host.")
def ls_cmd(show_all: bool, as_json: bool, boot_only: bool, host: str | None) -> None:
    """List registered agents in plain text (pipe-friendly).

    Output: name <TAB> category <TAB> path, or full records with --json.
    """
    from . import hosts as _hosts

    agents = config.load_agents_normalized() if show_all else config.active_agents()
    if boot_only:
        agents = [a for a in agents if a.get("boot")]
    if host:
        want = _hosts.normalize_key(host)
        agents = [a for a in agents if _hosts.normalize_key(a.get("host")) == want]
    if as_json:
        # An empty result is still valid JSON, so a caller can parse
        # unconditionally instead of special-casing no output.
        click.echo(json.dumps([_record(a) for a in agents], indent=2))
        return
    if not agents:
        return
    name_width = max(len(a["name"]) for a in agents)
    cat_width = max((len(a.get("category", "")) for a in agents), default=0)
    for a in agents:
        cat = a.get("category", "")
        print(f"{a['name']:<{name_width}}\t{cat:<{cat_width}}\t{a['path']}")


# ---------------------------------------------------------------------------
# Picker mode (default when no subcommand given)
